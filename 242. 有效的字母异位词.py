class Solution:
    # 定义一个名为 Solution 的类。
    # LeetCode 等算法平台通常使用这种标准模板，
    # 解题函数一般都定义在 Solution 类中。

    def isAnagram(self, s: str, t: str) -> bool:
        # 定义成员方法 isAnagram，用于判断两个字符串是否为字母异位词。
        #
        # 参数：
        # self：当前 Solution 实例本身。
        # s: str：第一个字符串。
        # t: str：第二个字符串。
        #
        # -> bool：
        # 返回布尔值。
        # True  表示两个字符串是字母异位词。
        # False 表示两个字符串不是字母异位词。

        # 第一层判断：比较两个字符串的长度。
        # 如果长度不同，说明字符总数不同，
        # 因此不可能由完全相同数量的字符组成。
        if len(s) != len(t):
            return False

        # 创建一个长度为 26 的列表，
        # 每个元素初始值都为 0。
        #
        # 题目规定字符串只包含小写英文字母 a-z，
        # 所以可以用 26 个位置分别记录 26 个字母的出现次数。
        #
        # 下标对应关系：
        # counts[0]  -> 'a'
        # counts[1]  -> 'b'
        # ...
        # counts[25] -> 'z'
        counts = [0] * 26

        # 遍历字符串 s 中的每一个字符。
        for ch in s:
            # ord(ch) 可以得到字符对应的 Unicode 码点。
            #
            # 例如：
            # ord('a') = 97
            # ord('b') = 98
            #
            # 因此：
            # ord(ch) - ord('a')
            # 可以把 a-z 映射到 0-25。
            #
            # 例如：
            # 'a' -> 97 - 97 = 0
            # 'b' -> 98 - 97 = 1
            # 'z' -> 122 - 97 = 25
            #
            # 每遇到一个字符，就让对应位置的计数 +1。
            counts[ord(ch) - ord('a')] += 1

        # 遍历第二个字符串 t。
        for ch in t:
            # 将当前字符转换成 0-25 的数组下标。
            idx = ord(ch) - ord('a')

            # 从之前统计的字符数量中减去 1。
            #
            # 可以理解为：
            # s 中出现一个字符时记 +1，
            # t 中出现一个相同字符时记 -1。
            #
            # 如果两个字符串字符数量完全一致，
            # 最终所有位置都应该变回 0。
            counts[idx] -= 1

            # 如果某个位置变成负数，
            # 说明 t 中这个字符出现的次数
            # 已经超过了 s 中这个字符出现的次数。
            #
            # 因此可以立即判断：
            # s 和 t 不可能是字母异位词。
            if counts[idx] < 0:
                return False

        # 如果程序能够执行到这里，说明：
        #
        # 1. s 和 t 长度相等；
        # 2. t 中不存在某个字符数量超过 s 的情况。
        #
        # 在总长度相等的前提下，
        # 这意味着所有字符出现次数都完全对应，
        # 最终 counts 中的所有元素都会是 0。
        #
        # 因此两个字符串是字母异位词。
        return True