# ============================================================
# 思路一：最直观的“切积木法”（暴力枚举）
# ============================================================

# 如果你手里有一根长为 n 的积木，想看它是不是由几个一模一样的小积木连成的，
# 那么小积木的长度一定能整除总长度。
#
# 例如：
# 假设总长度是 6，那么最小单位的长度只可能是 1、2、3。
#
# 长度不可能是 4 或 5，
# 因为 6 没办法被 4 或 5 完整拼满。
#
# 小积木最长也只能是原长度的一半，
# 因为题目要求“重复”，所以至少要重复 2 次。
#
#
# 做法：
#
# 拿前 k 个字符作为“模板子串”，
# 看这个模板不断重复之后，能不能正好拼成原字符串。
#
#
# 例如：
#
# s = "abcabcabc"
# 长度 n = 9
#
# 1. 尝试长度 k = 1
#
#    模板：
#    "a"
#
#    重复 9 次：
#    "aaaaaaaaa"
#
#    不等于原字符串，所以失败。
#
#
# 2. 尝试长度 k = 2
#
#    9 不能被 2 整除，
#    说明长度为 2 的子串不可能完整拼成长度为 9 的字符串，
#    所以直接跳过。
#
#
# 3. 尝试长度 k = 3
#
#    模板：
#    "abc"
#
#    9 // 3 = 3
#
#    重复 3 次：
#    "abc" * 3
#
#    得到：
#    "abcabcabc"
#
#    和原字符串完全相同，
#    所以返回 True。


class Solution:
    def repeatedSubstringPattern(self, s: str) -> bool:
        # 获取字符串长度
        n = len(s)

        # 枚举可能的重复子串长度
        #
        # 最短是 1
        # 最长只能到原字符串长度的一半
        #
        # 例如 n = 6：
        # k 只需要尝试 1、2、3
        for k in range(1, n // 2 + 1):

            # 只有 k 能整除 n，
            # 长度为 k 的子串才有可能完整拼成 s
            if n % k == 0:

                # 取前 k 个字符作为模板子串
                sub = s[:k]

                # 计算这个子串需要重复多少次
                repeat_count = n // k

                # 把模板重复 repeat_count 次
                # 如果结果正好等于原字符串，
                # 说明 s 是由重复子串构成的
                if sub * repeat_count == s:
                    return True

        # 所有可能的长度都尝试过，
        # 仍然没有找到符合条件的重复子串
        return False


# ============================================================
# 思路二：“旋转串”破案法
# ============================================================

# 可以把字符串想象成一个转盘或者闭合的圆环。
#
# 如果一个字符串是由周期性的子串重复组成的，
# 那么把前面一部分移动到后面，
# 在某个位置一定可以重新得到原字符串。
#
#
# 例如：
#
# s = "abab"
#
# 它其实是：
#
# "ab" + "ab"
#
# 如果把前面的 "ab" 挪到最后：
#
# "ab" + "ab"
#
# 还是：
#
# "abab"
#
#
# 但是如果：
#
# s = "aba"
#
# 它不是由某个更短的子串重复组成的。
#
# 怎么旋转都无法重新得到自己：
#
# "aba"
# 旋转一次 -> "baa"
# 旋转两次 -> "aab"
#
# 都不等于 "aba"。
#
#
# 那么怎么在代码里快速模拟“所有旋转结果”？
#
# 可以把字符串复制两份：
#
# s + s
#
#
# 例如：
#
# s = "abab"
#
# s + s：
#
# a b a b a b a b
#
#
# 把最前面和最后面各删掉一个字符：
#
#   b a b a b a
#
#
# 此时原字符串：
#
# "abab"
#
# 仍然可以在里面找到。
#
# 所以说明它是重复字符串。
#
#
# ------------------------------------------------------------
# 非重复字符串例子
# ------------------------------------------------------------
#
# s = "aba"
#
# 拼两份：
#
# a b a a b a
#
# 去掉第一个和最后一个字符：
#
# b a a b
#
# 也就是：
#
# "baab"
#
# 在 "baab" 里面找不到 "aba"，
# 所以返回 False。
#
#
# ------------------------------------------------------------
# 重复字符串例子
# ------------------------------------------------------------
#
# s = "abab"
#
# 拼两份：
#
# a b a b a b a b
#
# 去掉第一个和最后一个字符：
#
# b a b a b a
#
# 也就是：
#
# "bababa"
#
# 可以在里面找到：
#
# "abab"
#
# 所以返回 True。


class Solution:
    def repeatedSubstringPattern(self, s: str) -> bool:
        # 把两份 s 拼在一起
        #
        # 然后去掉最前面和最后面各一个字符，
        # 防止直接匹配到原来的那一份 s
        #
        # 如果剩下的字符串中还能找到完整的 s，
        # 说明 s 存在周期性，也就是由重复子串构成
        return s in (s + s)[1:-1]


# ============================================================
# 思路三：KMP 前缀表（经典解法）
# ============================================================

# 这个方法利用 KMP 算法中的前缀表。
#
# 前缀表记录的是：
#
# 截止到当前位置，
# 当前字符串的“最长相等前缀和后缀”的长度。
#
#
# 例如：
#
# s = "ababab"
#
# 最长的相等前后缀是：
#
# 前缀：
# "abab"
#
# 后缀：
# "abab"
#
# 所以最长相等前后缀长度：
#
# longest_border = 4
#
#
# 原字符串长度：
#
# n = 6
#
# 那么真正的重复单元长度就是：
#
# n - longest_border
#
# 也就是：
#
# 6 - 4 = 2
#
#
# 长度为 2 的子串就是：
#
# "ab"
#
# 而：
#
# 6 % 2 == 0
#
# 说明长度为 2 的子串可以完整重复拼成长度为 6 的字符串。
#
# 最终：
#
# "ab" * 3
#
# 得到：
#
# "ababab"
#
#
# 因此判断条件是：
#
# 1. 最长相等前后缀长度必须大于 0
#
#    longest_border > 0
#
#
# 2. 原字符串长度 n 必须能够整除重复单元长度
#
#    n - longest_border
#
#    也就是：
#
#    n % (n - longest_border) == 0
#
#
# 两个条件同时满足，
# 就说明字符串由某个更短的子串重复构成。


class Solution:
    def repeatedSubstringPattern(self, s: str) -> bool:
        # 获取字符串长度
        n = len(s)

        # 长度小于等于 1 时，
        # 不可能由更短的非空子串重复构成
        if n <= 1:
            return False

        # 创建 KMP 前缀表
        #
        # next_arr[i] 表示：
        # s[0:i+1] 这一段字符串中，
        # 最长相等前缀和后缀的长度
        next_arr = [0] * n

        # j 表示当前已经匹配成功的前缀长度
        j = 0

        # 从下标 1 开始遍历
        #
        # 因为只有一个字符时，
        # 不存在非空的“相等前缀和后缀”
        for i in range(1, n):

            # 如果当前字符 s[i]
            # 和前缀位置 s[j] 不相同，
            # 就不断缩短当前已经匹配的前缀长度
            #
            # j 不直接变成 0，
            # 而是利用之前已经计算好的前缀表进行回退
            while j > 0 and s[i] != s[j]:
                j = next_arr[j - 1]

            # 如果当前字符和前缀字符相同，
            # 说明相等前后缀长度可以增加 1
            if s[i] == s[j]:
                j += 1

            # 保存当前位置的最长相等前后缀长度
            next_arr[i] = j

        # 最后一个位置保存的值，
        # 就是整个字符串的最长相等前后缀长度
        longest_border = next_arr[-1]

        # 如果：
        #
        # 1. longest_border > 0
        #
        #    说明字符串存在非空的相等前后缀
        #
        # 2. n % (n - longest_border) == 0
        #
        #    说明重复单元长度能够完整地拼成整个字符串
        #
        # 那么字符串就是由重复子串构成的
        return longest_border > 0 and n % (n - longest_border) == 0